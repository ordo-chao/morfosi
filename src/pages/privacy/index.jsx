/* -------------------- small components -------------------- */

function AccordionSection({ section, expanded, onToggle, colors }) {
  const styles = makeStyles(colors);
  return (
    <View style={styles.section}>
      <TouchableOpacity
        style={styles.sectionHeader}
        onPress={onToggle}
        activeOpacity={0.7}
        accessibilityRole="button"
        accessibilityState={{ expanded }}
        accessibilityLabel={`Section ${section.number}: ${section.title}`}
      >
        <Text style={styles.sectionNumber}>{section.number}</Text>
        <Text style={styles.sectionTitle}>{section.title}</Text>
        <Ionicons
          name={expanded ? 'chevron-up' : 'chevron-down'}
          size={16}
          color={colors.fgMuted}
        />
      </TouchableOpacity>

      {expanded ? (
        <View style={styles.sectionBody}>
          <Text style={styles.sectionSummary}>{section.summary}</Text>

          {section.bullets?.length > 0 && (
            <View style={styles.bullets}>
              {section.bullets.map((b, i) => (
                <View key={i} style={styles.bulletRow}>
                  <Text style={styles.bulletDot}>•</Text>
                  <Text style={styles.bulletText}>{b}</Text>
                </View>
              ))}
            </View>
          )}

          {section.body ? (
            <Text style={styles.sectionParagraph}>{section.body}</Text>
          ) : null}
        </View>
      ) : null}
    </View>
  );
}

function ActionButton({ label, icon, onPress, colors }) {
  const styles = makeStyles(colors);
  return (
    <TouchableOpacity
      style={styles.actionBtn}
      onPress={onPress}
      activeOpacity={0.7}
      accessibilityRole="button"
      accessibilityLabel={label}
    >
      <Ionicons name={icon} size={14} color={colors.fg} />
      <Text style={styles.actionBtnText}>{label}</Text>
      <Ionicons name="chevron-forward" size={14} color={colors.fgMuted} />
    </TouchableOpacity>
  );
}

/* -------------------- screen -------------------- */

export default function Privacy({ navigation }) {
  const { colors } = useTheme();
  const styles = makeStyles(colors);

  // Start with section 1 expanded for context — the rest closed.
  const [openKey, setOpenKey] = useState('collect');

  const toggle = (key) => {
    setOpenKey((current) => (current === key ? null : key));
  };

  const onDownloadPdf = () => {
    if (!META.pdfUrl) {
      Alert.alert('Not available', 'The PDF will be available shortly.');
      return;
    }
    Linking.openURL(META.pdfUrl).catch(() =>
      Alert.alert('Could not open PDF', META.pdfUrl)
    );
  };

  const onViewFullPolicy = () => {
    Linking.openURL(META.fullTextUrl).catch(() =>
      Alert.alert('Could not open', META.fullTextUrl)
    );
  };

  const onViewWhatChanged = () => {
    navigation?.navigate('PrivacyDiff', { from: META.changedAt, to: META.version });
  };

  const onRequestData = () => {
    navigation?.navigate('DownloadData');
  };

  const onRequestCorrection = () => {
    navigation?.navigate('ProfileCorrection');
  };

  const onContactOfficer = () => {
    Linking.openURL(`mailto:${META.privacyEmail}?subject=Privacy%20request`).catch(
      () => Alert.alert('Could not open email', META.privacyEmail)
    );
  };

  return (
    <Layout>
    <View style={styles.page}>
      {/* Header */}
      <View style={styles.header}>
        <TouchableOpacity onPress={() => navigation?.goBack()} hitSlop={8}>
          <Ionicons name="chevron-back" size={22} color={colors.fg} />
        </TouchableOpacity>
        <Text style={styles.headerTitle}>PRIVACY POLICY</Text>
        <TouchableOpacity onPress={onDownloadPdf} hitSlop={8}>
          <Ionicons name="download-outline" size={20} color={colors.fg} />
        </TouchableOpacity>
      </View>

      <ScrollView
        style={{ flex: 1 }}
        contentContainerStyle={styles.scrollContent}
        showsVerticalScrollIndicator={false}
      >
        {/* ===== META ===== */}
        <View style={styles.metaBlock}>
          <Text style={styles.metaLine}>
            <Text style={styles.metaKey}>Effective:</Text> {META.effective}
          </Text>
          <Text style={styles.metaLine}>
            <Text style={styles.metaKey}>Last updated:</Text> {META.updated}
            <Text style={styles.metaKey}>  ·  v{META.version}</Text>
          </Text>
          {META.changedAt ? (
            <TouchableOpacity onPress={onViewWhatChanged} hitSlop={6}>
              <Text style={styles.metaLink}>WHAT CHANGED? →</Text>
            </TouchableOpacity>
          ) : null}
        </View>

        {/* ===== CONTENTS ===== */}
        <Text style={styles.sectionTitleLarge}>CONTENTS</Text>
        <View style={styles.contentsBlock}>
          {SECTIONS.map((s) => (
            <TouchableOpacity
              key={s.key}
              style={styles.contentsRow}
              onPress={() => setOpenKey(s.key)}
              activeOpacity={0.7}
            >
              <Text style={styles.contentsNumber}>{s.number}.</Text>
              <Text style={styles.contentsLabel}>{s.title}</Text>
            </TouchableOpacity>
          ))}
        </View>

        {/* ===== ACCORDION SECTIONS ===== */}
        {SECTIONS.map((s) => (
          <AccordionSection
            key={s.key}
            section={s}
            expanded={openKey === s.key}
            onToggle={() => toggle(s.key)}
            colors={colors}
          />
        ))}

        {/* ===== RIGHTS ACTIONS ===== */}
        <Text style={styles.sectionTitleLarge}>TAKE ACTION</Text>
        <View style={styles.actionsBlock}>
          <ActionButton
            label="Request my data"
            icon="download-outline"
            onPress={onRequestData}
            colors={colors}
          />
          <ActionButton
            label="Request correction"
            icon="create-outline"
            onPress={onRequestCorrection}
            colors={colors}
          />
          <ActionButton
            label="Contact privacy officer"
            icon="mail-outline"
            onPress={onContactOfficer}
            colors={colors}
          />
        </View>

        {/* ===== LEGAL FOOTER ===== */}
        <View style={styles.legalBlock}>
          <Text style={styles.legalText}>
            This policy complies with the Kenya Data Protection Act (2019)
            and GDPR where applicable.
          </Text>
          <TouchableOpacity onPress={onViewFullPolicy} hitSlop={6}>
            <Text style={styles.legalLink}>VIEW COMPLETE POLICY →</Text>
          </TouchableOpacity>
        </View>
      </ScrollView>
    </View>
    </Layout>
  );
}